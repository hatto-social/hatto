//! Bindings from Dart to Anki's rslib.
//!
//! Collection calls go through `init_backend` (a `BackendInit` protobuf) and
//! `Backend::run_service_method`. Nothing else in rslib is used to read or write
//! a collection. rslib is linked once, from `rslib_core`. This crate is the
//! only cdylib (`librslib_bridge.so`). Import staging calls `hatto_import`,
//! which uses that same `rslib_core`.

pub mod api;
pub mod export_contract;
#[cfg(not(frb_expand))]
mod import_stage;
mod package_inspect;

// Generated by `flutter_rust_bridge_codegen generate`. Not hand-edited.
mod frb_generated;

/// `prepare_runtime` writes the process temp directory. Tests that open a
/// collection take this so they do not replace each other's temp directory.
#[cfg(test)]
pub(crate) fn lock_bridge_runtime() -> std::sync::MutexGuard<'static, ()> {
    static LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());
    LOCK.lock().unwrap_or_else(|err| err.into_inner())
}
