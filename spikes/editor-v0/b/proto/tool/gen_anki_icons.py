#!/usr/bin/env python3
# Regenerates lib/anki_icon_data.dart from JSON dumps taken from the running Anki 26.09.3 editor DOM
# (see /workspace/editor-spikes/anki-run/{icons_dump.json}, /tmp/tagsvg.json copy in ../../anki-run/tagsvg.json).
import json
R='/workspace/editor-spikes/anki-run/'
d={x['role']:x for x in json.load(open(R+'icons_dump.json'))}
t=json.load(open(R+'tagsvg.json'))
trash=[x for x in t if x.get('i')==2][0]['d'][0]
tag=[x for x in t if x.get('i')==0][0]['d'][0]
def paths(role,idx=0): return d[role]['svgs'][idx]['d']
icons={
 'gear':('mdi','cog',paths('toolbar0'),24),'bold':('bi','type-bold',paths('toolbar1'),16),'italic':('bi','type-italic',paths('toolbar2'),16),
 'underline':('bi','type-underline',paths('toolbar3'),16),'superscript':('mdi','format-superscript',paths('toolbar4'),24),
 'subscript':('mdi','format-subscript',paths('toolbar5'),24),'textColor':('mdi','format-color-text',paths('toolbar6',0),24),
 # toolbar6 path 1 is a plain rectangle, not an mdi/bootstrap glyph. anki_ui.dart draws it. Do not emit it here.
 'highlight':('mdi','format-color-highlight',paths('toolbar8',0),24),
 'chevronDown':('mdi','chevron-down',paths('toolbar7'),24),'eraser':('bi','eraser',paths('toolbar10'),16),
 'listUl':('bi','list-ul',paths('toolbar12'),16),'listOl':('bi','list-ol',paths('toolbar13'),16),'align':('bi','text-paragraph',paths('toolbar14'),16),
 'attach':('mdi','paperclip',paths('toolbar15'),24),'mic':('bi','mic',paths('toolbar16'),16),'equation':('mdi','function-variant',paths('toolbar17'),24),
 'codeTags':('mdi','code-tags',paths('fieldbadge2'),24),'tag':('mdi','tag-outline',[tag],24),'trash':('mdi','delete',[trash],24),
}
dq=lambda s:"r'"+s+"'"
out=["// GENERATED by tool/gen_anki_icons.py from the running Anki 26.09.3 editor DOM (svg path data). DO NOT hand-edit.",
"// Icon sources (per Anki's ts/licenses.json and ts/lib/components/icons.ts): @mdi/svg 7.4.47 (Apache-2.0, Pictogrammers/Templarian),",
"// bootstrap-icons 1.11.3 (MIT). Licensing sign-off for Hatto is an OPEN QUESTION (see DMITRY_EDITOR_ANKI_DESIGN_REVIEW.md Q4).",
"// ignore_for_file: lines_longer_than_80_chars",
"class IconData2 { const IconData2(this.set, this.name, this.viewBox, this.paths); final String set, name; final double viewBox; final List<String> paths; }",
"const Map<String, IconData2> kAnkiIcons = {"]
for k,(s,n,p,vb) in icons.items(): out.append(f"  '{k}': IconData2('{s}', '{n}', {vb}, [{', '.join(dq(x) for x in p)}]),")
out.append("};")
open('lib/anki_icon_data.dart','w').write("\n".join(out)+"\n")
