//! Build the service/method index from Anki 26.09.3's protobuf sources.
//!
//! rslib dispatches `run_service_method` with indices from `anki_proto_gen::get_services`
//! over the descriptor pool (not the raw prost file index, and not a stable ABI).
//! This script runs the same helper on the same proto files so Dart and Rust share one table.

use std::fs;
use std::path::PathBuf;

use anki_proto_gen::get_services;
use anyhow::Context;
use prost_reflect::DescriptorPool;

fn main() -> anyhow::Result<()> {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let proto_root = manifest_dir.join("../../../third_party/anki/proto");
    let anki_dir = proto_root.join("anki");
    println!("cargo:rerun-if-changed={}", anki_dir.display());

    let mut protos = Vec::new();
    for entry in fs::read_dir(&anki_dir).with_context(|| format!("read {}", anki_dir.display()))? {
        let path = entry?.path();
        if path.extension().and_then(|ext| ext.to_str()) == Some("proto") {
            println!("cargo:rerun-if-changed={}", path.display());
            protos.push(path);
        }
    }
    protos.sort();
    if protos.is_empty() {
        anyhow::bail!("no .proto files under {}", anki_dir.display());
    }

    let out_dir = PathBuf::from(std::env::var("OUT_DIR")?);
    let descriptor_path = out_dir.join("bridge_descriptors.bin");
    // Generated Rust is unused; the descriptor set is what get_services reads.
    // File order matches rslib/proto/rust.rs (sorted paths) so service indices agree.
    prost_build::Config::new()
        .file_descriptor_set_path(&descriptor_path)
        .out_dir(&out_dir)
        .compile_protos(&protos, &[proto_root])
        .context("compile Anki protos for the service index")?;

    let pool = DescriptorPool::decode(fs::read(&descriptor_path)?.as_slice())?;
    let (_collection, backend) = get_services(&pool);

    let mut entries = String::new();
    for service in &backend {
        // rslib's dispatcher omits the frontend service. Indices of the others stay as-is.
        if service.name == "BackendFrontendService" {
            continue;
        }
        for method in service.all_methods() {
            entries.push_str(&format!(
                "    ServiceMethod {{ service: {:?}, method: {:?}, service_index: {}, method_index: {} }},\n",
                service.name,
                method.name,
                u32::try_from(service.index).context("service index")?,
                u32::try_from(method.index).context("method index")?,
            ));
        }
    }

    let generated = format!(
        r#"// Generated by packages/rslib_bridge/rust/build.rs from Anki 26.09.3 protos.
// Do not edit. Service and method numbers are not a stable ABI.

#[derive(Clone, Copy, Debug)]
pub struct ServiceMethod {{
    pub service: &'static str,
    pub method: &'static str,
    pub service_index: u32,
    pub method_index: u32,
}}

pub static SERVICE_METHODS: &[ServiceMethod] = &[
{entries}];
"#
    );
    fs::write(out_dir.join("service_index.rs"), generated)?;
    Ok(())
}
