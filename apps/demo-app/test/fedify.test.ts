import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { runFedifyLab } from "../src/fedify/lab";

test("two Fedify instances exchange deck revisions", { timeout: 120_000 }, async () => {
  const report = await runFedifyLab();
  const file = path.join(process.cwd(), "results", "fedify.json");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(report, null, 2));
  const pub = report.publicUpdate as {
    digestOk: boolean;
    dispatcherStatus: number;
    dispatcherBody: { "hatto:rev"?: number; "hatto:guid"?: string };
    deliver: { error: string | null; posts: Array<{ status: number }> };
  };
  assert.equal(pub.deliver.error, null, JSON.stringify(pub.deliver));
  assert.equal(pub.deliver.posts[0]?.status, 202);
  assert.equal(pub.dispatcherStatus, 200);
  assert.equal(pub.dispatcherBody["hatto:rev"], 2);
  assert.equal(pub.dispatcherBody["hatto:guid"], "public-deck");
  assert.equal(pub.digestOk, true);

  const embed = report.embed as {
    singleParse: string;
    singlePost: { status: number; body: string };
    arrayCompact: { type: string; hattoRev: unknown };
    arraySend: { posts: Array<{ status: number; hattoKeys: string[] }> };
    arrayPost: { status: number };
    listener: Array<{ embedded?: { "hatto:rev"?: number; type?: unknown } }>;
  };
  assert.match(embed.singleParse, /Invalid type: hatto:Deck/);
  assert.equal(embed.singlePost.status, 400);
  assert.equal(embed.arrayCompact.type, "Object");
  assert.equal(embed.arrayCompact.hattoRev, null);
  assert.equal(embed.arraySend.posts[0]?.status, 202);
  assert.deepEqual(embed.arraySend.posts[0]?.hattoKeys, []);
  assert.equal(embed.arrayPost.status, 202);
  assert.equal(embed.listener.at(-1)?.embedded?.["hatto:rev"], 2);

  const note = report.createNote as {
    directCompact: { keys: string[]; hatto: string[] };
    separateDispatcher: { status: number; body: Record<string, unknown> };
  };
  assert.deepEqual(note.directCompact.hatto, []);
  assert.ok(note.directCompact.keys.includes("content"));
  assert.equal(note.separateDispatcher.status, 200);
  assert.equal(note.separateDispatcher.body["hatto:event"], "deck-published");
  assert.equal(note.separateDispatcher.body["hatto:streakDays"], 12);

  const dedup = report.dedup as {
    duplicate: { calls: number[]; reducer: { applied: number; duplicates: number; head: number }; inbox: number[] };
    reverse: { arrival: number[]; head: number; olderKept: number };
  };
  assert.deepEqual(dedup.duplicate.calls, [1, 1]);
  assert.equal(dedup.duplicate.reducer.duplicates, 1);
  assert.equal(dedup.duplicate.reducer.head, 1);
  assert.deepEqual(dedup.duplicate.inbox, [202, 202, 202]);
  assert.deepEqual(dedup.reverse.arrival, [3, 1]);
  assert.equal(dedup.reverse.head, 3);
  assert.equal(dedup.reverse.olderKept, 1);

  const priv = report.privateDeck as {
    unsignedStatus: number;
    strangerStatus: number;
    ownerStatus: number;
    digestOk: boolean;
    expiredStatus: number;
    ownerHattoRev: number;
  };
  assert.equal(priv.unsignedStatus, 404);
  assert.equal(priv.strangerStatus, 404);
  assert.equal(priv.ownerStatus, 200);
  assert.equal(priv.ownerHattoRev, 1);
  assert.equal(priv.digestOk, true);
  assert.equal(priv.expiredStatus, 404);

  const fork = report.forkMr as {
    withContext: { send: { error: string | null; posts: Array<{ status: number }> }; heard: { origin: string; context: string; hatto: string[] } };
    withoutContext: { send: { posts: Array<{ status: number }> }; heard: { origin: string; context: string | null } };
    embedded: { heard: { embeddedHatto: string[]; embeddedOrigin: string | null; embeddedUrl: { digestMultibase?: string } | null } };
    fetch: { byteEqualToOriginal: boolean; signedByteEqual: boolean; schemaErrors: string[]; digestOk: boolean; unsignedBytes: number; originalBytes: number; origin: string };
    control: { parsed: string; send: { posts: Array<{ activityHatto: string[] }> } };
    acceptFlow: {
      offerHeard: { type: string; summary: string; content: string; target: string; hostMatch: boolean; readable: boolean };
      offerSend: { posts: Array<{ status: number }> };
      acceptHeard: { type: string; result: string; object: string; ownerMatch: boolean };
      acceptSend: { posts: Array<{ status: number }> };
      revAcceptHeard: { result: string };
      revAcceptSend: { posts: Array<{ status: number }> };
    };
    rejectFlow: { rejectHeard: { type: string; content: string }; rejectSend: { posts: Array<{ status: number }> } };
    checks: {
      hostMismatch: { hostMatch: boolean };
      hostMismatchSend: { posts: Array<{ status: number }> };
      ownerMismatch: { ownerMatch: boolean };
      readShared: { readable: boolean };
      readClosed: { readable: boolean };
      sharedGet: number;
      closedGet: number;
      closedUnsigned: number;
    };
    order: { hattoRev: number[]; idNumbers: number[]; head: number; olderKept: number };
    dedup: {
      ttl: string;
      wallClockWaitMs: number;
      sameId: { listener: number; kv: boolean; first: { posts: Array<{ status: number }> }; second: { posts: Array<{ status: number }> } };
      at24h: { listener: number; kv: boolean };
      at25h: { listener: number; kv: null; app: { applied: number; duplicates: number } };
      resubmit: { sameAsDup: boolean; listener: number; app: { applied: number; duplicates: number } };
    };
    acceptBeforeOffer: { order: string[] };
    gets: Array<{ status: number; id: string; requested: string }>;
  };
  assert.equal(fork.withContext.send.error, null);
  assert.equal(fork.withContext.send.posts[0]?.status, 202);
  assert.equal(fork.withContext.heard.origin.endsWith("/decks/fork-source/revs/4"), true);
  assert.equal(fork.withContext.heard.context.endsWith("/decks/fork-source"), true);
  assert.deepEqual(fork.withContext.heard.hatto, []);
  assert.equal(fork.withoutContext.send.posts[0]?.status, 202);
  assert.equal(fork.withoutContext.heard.origin.endsWith("/decks/fork-source/revs/4"), true);
  assert.equal(fork.withoutContext.heard.context, null);
  assert.deepEqual(fork.embedded.heard.embeddedHatto, []);
  assert.equal(fork.embedded.heard.embeddedOrigin, null);
  assert.equal(fork.embedded.heard.embeddedUrl?.digestMultibase, undefined);
  assert.equal(fork.fetch.byteEqualToOriginal, true);
  assert.equal(fork.fetch.signedByteEqual, true);
  assert.equal(fork.fetch.unsignedBytes, fork.fetch.originalBytes);
  assert.equal(fork.fetch.unsignedBytes, 733);
  assert.equal(fork.fetch.origin.endsWith("/decks/fork-source/revs/4"), true);
  assert.deepEqual(fork.fetch.schemaErrors, []);
  assert.equal(fork.fetch.digestOk, true);
  assert.deepEqual(JSON.parse(fork.control.parsed).hatto, []);
  assert.deepEqual(fork.control.send.posts[0]?.activityHatto, []);
  assert.equal(fork.acceptFlow.offerSend.posts[0]?.status, 202);
  assert.equal(fork.acceptFlow.offerHeard.type, "Offer");
  assert.equal(fork.acceptFlow.offerHeard.summary, "포크를 머지해 주세요");
  assert.equal(fork.acceptFlow.offerHeard.content, "fork-copy의 rev 1을 원본에 반영하고 싶습니다");
  assert.equal(fork.acceptFlow.offerHeard.target.endsWith("/decks/fork-source"), true);
  assert.equal(fork.acceptFlow.offerHeard.hostMatch, true);
  assert.equal(fork.acceptFlow.offerHeard.readable, true);
  assert.equal(fork.acceptFlow.acceptSend.posts[0]?.status, 202);
  assert.equal(fork.acceptFlow.acceptHeard.type, "Accept");
  assert.equal(fork.acceptFlow.acceptHeard.ownerMatch, true);
  assert.equal(fork.acceptFlow.acceptHeard.result.endsWith("/activities/merges/fork-copy/revs/1/n/1"), true);
  assert.equal(fork.acceptFlow.acceptHeard.object.includes("/activities/offers/fork-copy/revs/1/targets/"), true);
  assert.equal(fork.acceptFlow.revAcceptSend.posts[0]?.status, 202);
  assert.equal(fork.acceptFlow.revAcceptHeard.result.endsWith("/decks/fork-source/revs/5"), true);
  assert.equal(fork.rejectFlow.rejectSend.posts[0]?.status, 202);
  assert.equal(fork.rejectFlow.rejectHeard.type, "Reject");
  assert.equal(fork.rejectFlow.rejectHeard.content, "범위가 원본과 다릅니다");
  assert.equal(fork.checks.hostMismatch.hostMatch, false);
  assert.equal(fork.checks.hostMismatchSend.posts[0]?.status, 202);
  assert.equal(fork.checks.ownerMismatch.ownerMatch, false);
  assert.equal(fork.checks.readShared.readable, true);
  assert.equal(fork.checks.readClosed.readable, false);
  assert.equal(fork.checks.sharedGet, 200);
  assert.equal(fork.checks.closedGet, 404);
  assert.equal(fork.checks.closedUnsigned, 404);
  assert.deepEqual(fork.order.hattoRev, [2, 1]);
  assert.deepEqual(fork.order.idNumbers, [9, 8]);
  assert.equal(fork.order.head, 2);
  assert.equal(fork.order.olderKept, 1);
  assert.equal(fork.dedup.ttl, "PT24H");
  assert.equal(fork.dedup.wallClockWaitMs, 0);
  assert.equal(fork.dedup.sameId.listener, 1);
  assert.equal(fork.dedup.sameId.kv, true);
  assert.equal(fork.dedup.sameId.first.posts[0]?.status, 202);
  assert.equal(fork.dedup.sameId.second.posts[0]?.status, 202);
  assert.equal(fork.dedup.at24h.listener, 1);
  assert.equal(fork.dedup.at24h.kv, true);
  assert.equal(fork.dedup.at25h.listener, 2);
  assert.equal(fork.dedup.at25h.kv, null);
  assert.equal(fork.dedup.at25h.app.applied, 1);
  assert.equal(fork.dedup.at25h.app.duplicates, 1);
  assert.equal(fork.dedup.resubmit.sameAsDup, false);
  assert.equal(fork.dedup.resubmit.listener, 1);
  assert.equal(fork.dedup.resubmit.app.applied, 2);
  assert.equal(fork.dedup.resubmit.app.duplicates, 1);
  assert.deepEqual(fork.acceptBeforeOffer.order, ["accept", "offer"]);
  assert.equal(fork.gets.length, 21);
  assert.equal(fork.gets.every((item) => item.status === 200 && item.id === item.requested), true);
});
